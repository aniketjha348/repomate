"use client";

import { API_URL } from "@/lib/config";
import { buttonClasses } from "@/components/ui/button";
import type { Artifact, ArtifactDocument } from "@/lib/types";
import { formatBytes } from "@/lib/utils";

function ArtifactRow({
  name,
  kind,
  size,
  href,
}: {
  name: string;
  kind: string;
  size: number;
  href: string;
}) {
  return (
    <div className="flex flex-wrap items-center justify-between gap-2 rounded-lg border border-border/70 bg-muted/20 px-3 py-2">
      <div className="min-w-0">
        <p className="break-all font-mono text-xs text-foreground">{name}</p>
        <p className="mt-0.5 font-mono text-[10px] text-muted-foreground">
          {kind} · {formatBytes(size)}
        </p>
      </div>
      <a
        href={href}
        target="_blank"
        rel="noreferrer"
        download
        className={buttonClasses("outline", "sm")}
      >
        Download
      </a>
    </div>
  );
}

/** Every downloadable output of the run, including non-diff documents. */
export function ArtifactDownloads({
  runId,
  artifact,
  documents,
}: {
  runId: string;
  artifact?: Artifact | null;
  documents: ArtifactDocument[];
}) {
  if (!artifact && documents.length === 0) return null;

  return (
    <div className="space-y-2">
      <div className="grid gap-2 sm:grid-cols-2">
        {artifact ? (
          <ArtifactRow
            name={
              artifact.kind === "DOCS_DIFF"
                ? "documentation.patch"
                : artifact.kind === "TEST_DIFF"
                  ? "tests.patch"
                  : "contribution.patch"
            }
            kind={artifact.kind}
            size={new TextEncoder().encode(artifact.patch).length}
            href={`${API_URL}/api/runs/${encodeURIComponent(runId)}/artifacts/patch`}
          />
        ) : null}
        {documents.map((document) => (
          <ArtifactRow
            key={document.name}
            name={document.name}
            kind={document.kind}
            size={new TextEncoder().encode(document.content).length}
            href={`${API_URL}/api/runs/${encodeURIComponent(runId)}/artifacts/${encodeURIComponent(document.name)}`}
          />
        ))}
      </div>
      {artifact ? (
        <p className="font-mono text-[10px] text-muted-foreground/80">
          generated by {artifact.generated_by} · based on{" "}
          {artifact.based_on_commit.slice(0, 10)}
        </p>
      ) : null}
    </div>
  );
}
