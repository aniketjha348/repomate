"use client";

import { useMemo } from "react";
import { API_URL } from "@/lib/config";
import { parseUnifiedDiff, type DiffFile, type DiffLine } from "@/lib/diff";
import type { Artifact } from "@/lib/types";
import { buttonClasses } from "@/components/ui/button";
import { cn } from "@/lib/utils";

const LINE_CLASSES = {
  add: "bg-emerald-500/10 text-emerald-300",
  remove: "bg-red-500/10 text-red-300",
  context: "text-zinc-400",
  hunk: "bg-sky-500/5 text-sky-400",
  file: "text-muted-foreground/70",
} as const;

function DiffRow({ line }: { line: DiffLine }) {
  // The raw `diff --git` line is redundant — the file header shows the paths.
  if (line.type === "file" && line.text.startsWith("diff --git ")) return null;
  const showsOld = line.type === "remove" || line.type === "context";
  const showsNew = line.type === "add" || line.type === "context";
  return (
    <div
      className={cn(
        "flex whitespace-pre font-mono text-xs leading-5",
        LINE_CLASSES[line.type],
      )}
    >
      <span className="w-10 shrink-0 select-none pr-2 text-right text-muted-foreground/40">
        {showsOld ? (line.oldNo ?? "") : ""}
      </span>
      <span className="w-10 shrink-0 select-none pr-2 text-right text-muted-foreground/40">
        {showsNew ? (line.newNo ?? "") : ""}
      </span>
      <span className="min-w-0 flex-1 break-all pl-2">{line.text || " "}</span>
    </div>
  );
}

function FileDiff({ file }: { file: DiffFile }) {
  const [oldPath, newPath] = file.paths ?? [null, null];
  const label =
    oldPath && newPath && oldPath !== newPath
      ? `${oldPath} → ${newPath}`
      : (newPath ?? oldPath ?? "patch");
  const adds = file.lines.filter((l) => l.type === "add").length;
  const removes = file.lines.filter((l) => l.type === "remove").length;

  return (
    <div className="overflow-hidden rounded-lg border border-border">
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-border bg-muted/60 px-3 py-2">
        <p className="min-w-0 break-all font-mono text-xs font-medium text-foreground">
          {label}
        </p>
        <p className="shrink-0 font-mono text-[10px]">
          <span className="text-emerald-400">+{adds}</span>{" "}
          <span className="text-red-400">−{removes}</span>
        </p>
      </div>
      <div className="overflow-x-auto bg-background/40 scrollbar-thin">
        {file.lines.map((line, index) => (
          <DiffRow key={index} line={line} />
        ))}
      </div>
    </div>
  );
}

export function DiffViewer({
  runId,
  artifact,
}: {
  runId: string;
  artifact: Artifact;
}) {
  const files = useMemo(() => parseUnifiedDiff(artifact.patch), [artifact.patch]);

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex flex-wrap items-center gap-1.5">
          {artifact.affected_paths.map((path) => (
            <code
              key={path}
              className="rounded-full border border-border bg-muted px-2 py-0.5 font-mono text-xs text-muted-foreground"
            >
              {path}
            </code>
          ))}
        </div>
        <a
          href={`${API_URL}/api/runs/${encodeURIComponent(runId)}/artifacts/patch`}
          target="_blank"
          rel="noreferrer"
          download
          className={buttonClasses("outline", "sm")}
        >
          Download patch
        </a>
      </div>
      <p className="font-mono text-xs text-muted-foreground">
        based on {artifact.based_on_commit.slice(0, 10)} · generated by{" "}
        {artifact.generated_by}
      </p>
      {files.length > 0 ? (
        <div className="space-y-4">
          {files.map((file, index) => (
            <FileDiff key={index} file={file} />
          ))}
        </div>
      ) : (
        <p className="rounded-lg border border-dashed border-border p-6 text-center font-mono text-xs text-muted-foreground">
          Empty patch.
        </p>
      )}
    </div>
  );
}
