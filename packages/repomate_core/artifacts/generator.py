"""Documentation artifact generation.

The MVP generator appends a well-formed section to the planned docs file.
Content is derived from the task statement and cites the evidence records
it was built from, so a reviewer can trace every line back to the issue.
The workspace is always reset afterwards — the patch text is the only
lasting output, and verification re-applies it to a clean tree.
"""

from __future__ import annotations

import re
from typing import Optional

from repomate_core.contracts import (
    ArtifactKind,
    ContributionArtifact,
    ContributionPlan,
    EvidenceRecord,
)
from repomate_core.artifacts.patch import extract_affected_paths
from repomate_core.repository.workspace import RepoWorkspace

_MAX_SECTION_LINES = 60


def generate_docs_artifact(
    ws: RepoWorkspace,
    plan: ContributionPlan,
    task_text: str,
    evidence: list[EvidenceRecord],
) -> ContributionArtifact:
    change = next(
        (c for c in plan.planned_changes if c.change_type == "MODIFY"), None
    ) or (plan.planned_changes[0] if plan.planned_changes else None)
    if change is None:
        raise ValueError("plan has no planned changes to render")

    original = ws.read_text(change.path) if change.change_type == "MODIFY" else ""
    base_sha = ws.commit_sha

    title = _section_title(task_text)
    if _normalized(title) in _normalized(original):
        # Refuse duplicate sections — idempotence guard for re-runs.
        raise ValueError(f"section {title!r} already exists in {change.path}")

    if plan.content_draft:
        # Model-written content, used verbatim (bounded and fence-stripped
        # by the planner). When the draft opens with its own markdown
        # heading it becomes the section heading; otherwise RepoMate's
        # title is prepended for consistent structure.
        draft = plan.content_draft.strip()
        section = draft if draft.startswith("#") else f"## {title}\n\n{draft}\n"
        section = "\n".join(section.splitlines()[:_MAX_SECTION_LINES])
    else:
        section = _build_section(title, task_text, evidence, is_rst=change.path.endswith(".rst"))
    if change.change_type == "MODIFY":
        ws.write_text(change.path, original.rstrip() + "\n\n" + section + "\n")
    else:
        ws.write_text(change.path, section + "\n")
        ws.stage_intent_to_add(change.path)

    patch = ws.diff()
    ws.reset_hard()

    affected = extract_affected_paths(patch)
    return ContributionArtifact(
        kind=ArtifactKind.DOCS_DIFF,
        patch=patch,
        affected_paths=affected,
        based_on_commit=base_sha,
        generated_by=plan.planned_by,
    )


def _section_title(task_text: str) -> str:
    words = re.sub(r"\s+", " ", task_text).strip().rstrip(".!")
    # Drop leading task verbs so titles read like section names.
    words = re.sub(r"^(please\s+)?(add|write|create|document|documenting)\s+", "", words, flags=re.I)
    words = words[0].upper() + words[1:]
    if len(words) > 70:
        words = words[:69].rsplit(" ", 1)[0] + "…"
    return words or "Additional documentation"


def _build_section(
    title: str,
    task_text: str,
    evidence: list[EvidenceRecord],
    *,
    is_rst: bool,
) -> str:
    heading = title if not is_rst else title
    underline = "=" * min(len(heading), 72) if is_rst else None

    bullets: list[str] = []
    for sentence in [s.strip() for s in re.split(r"(?<=[.!?])\s+", task_text) if s.strip()][:4]:
        bullets.append(sentence)
    if not bullets:
        bullets.append(task_text.strip())

    cited = [e for e in evidence if not e.path.startswith("issue#")][:3]
    lines: list[str] = []
    if is_rst:
        lines.append(heading)
        lines.append(underline)
    else:
        lines.append(f"## {heading}")
    lines.append("")
    lines.append("This section addresses the following contribution task:")
    lines.append("")
    for bullet in bullets:
        marker = "- " if not is_rst else "* "
        lines.append(f"{marker}{bullet}")
    if cited:
        lines.append("")
        lines.append("Sources consulted while writing this section:")
        lines.append("")
        for record in cited:
            location = (
                f"{record.path}, lines {record.start_line}-{record.end_line}"
                if record.start_line is not None
                else record.path
            )
            lines.append(f"- {location}")
    lines.append("")
    lines.append("<!-- Generated by RepoMate; verify wording against project conventions. -->")

    # Bounded output guard: a pathological task text cannot blow up the diff.
    return "\n".join(lines[:_MAX_SECTION_LINES])


def _normalized(text: str) -> str:
    return re.sub(r"\s+", " ", text.lower()).strip(" #=")
