"""Integration tests: the full pipeline against a local git fixture.

The GitHub clone step is replaced with a local workspace factory so the
entire workflow (validate -> pin -> evidence -> plan -> artifact ->
verify -> publish) runs for real without network access.
"""

from pathlib import Path

import pytest

from repomate_core.contracts import ErrorCode, RepositoryInput, RunStatus, TaskSource
from repomate_core.orchestration.pipeline import PipelineConfig, run_pipeline
from repomate_core.orchestration.store import RunStore
from repomate_core.repository.workspace import RepoWorkspace


def _factory(local_repo: Path):
    def factory(ref, dest, config):
        return RepoWorkspace.from_local(local_repo)
    return factory


def _config(tmp_path: Path) -> PipelineConfig:
    return PipelineConfig(runs_root=tmp_path / "runs", keep_workspace=False)


def test_docs_task_completes_end_to_end(tmp_path, local_repo, docs_task_input):
    events = []
    record = run_pipeline(
        docs_task_input,
        config=_config(tmp_path),
        workspace_factory=_factory(local_repo),
        event_cb=events.append,
    )

    assert record.status is RunStatus.COMPLETED
    assert record.planner == "heuristic-v1"
    assert record.snapshot.commit_sha and record.snapshot.license.spdx_id == "MIT"
    # PS04 background insights: newcomer orientation + which tests to run.
    assert record.orientation is not None
    assert "fixture-project" in record.orientation.summary
    assert record.test_guidance is not None
    assert record.test_guidance.run_command == "python -m pytest -q"
    assert any(t.path == "tests/test_core.py" for t in record.test_guidance.relevant_tests)
    assert record.evidence, "documentation runs must cite evidence"
    assert record.artifact is not None
    assert record.artifact.affected_paths == ["README.md"]
    assert "## " in record.artifact.patch
    assert "Generated by RepoMate" in record.artifact.patch

    assert record.receipt is not None
    assert record.receipt.overall.value == "PASSED"
    by_name = {c.name: c for c in record.receipt.checks}
    assert by_name["patch-applies-on-pinned-commit"].status.value == "PASSED"
    assert by_name["patch-path-policy"].status.value == "PASSED"
    # Phase 4: the fixture's pytest suite executes in the process sandbox.
    suite = by_name["repository-test-suite"]
    assert suite.status.value == "PASSED"
    assert suite.exit_code == 0
    assert "pytest" in suite.command

    stages = [e.stage.value for e in events if e.status == "COMPLETED"]
    assert stages == [
        "VALIDATE_INPUT", "PIN_SNAPSHOT", "RETRIEVE_EVIDENCE",
        "PLAN", "GENERATE_ARTIFACT", "VERIFY", "PUBLISH",
    ]

    store = RunStore(tmp_path / "runs")
    assert store.artifact_path(record.run_id).is_file()
    assert not store.workspace_dir(record.run_id).exists(), "workspace must be cleaned up"
    persisted = store.load_run(record.run_id)
    assert persisted.status is RunStatus.COMPLETED
    assert store.load_events(record.run_id)


